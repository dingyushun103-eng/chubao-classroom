// ============ 随机题库生成器 ============
// 生成加减法口算题：q 为题目字符串，options 含 4 个选项（含正确答案），answer 为正确项下标
function genAddSub(min, max, count, maxSum = Infinity) {
  const rnd = (a, b) => Math.floor(Math.random() * (b - a + 1)) + a;
  const set = new Set(); // 去重
  let guard = 0;
  while (set.size < count && guard++ < count * 50) {
    const a = rnd(min, max);
    const b = rnd(min, max);
    let q, ans;
    if (Math.random() < 0.5 && a >= b) {
      ans = a - b;
      q = `${a} − ${b} = ?`;
    } else {
      ans = a + b;
      if (ans > maxSum) continue; // 和不超过上限（如“20以内”）
      q = `${a} + ${b} = ?`;
    }
    // 生成 3 个干扰选项（与正确答案不同且不重复）
    const opts = new Set([ans]);
    while (opts.size < 4) {
      const delta = rnd(1, Math.max(3, Math.ceil(ans * 0.2)));
      const wrong = Math.random() < 0.5 ? ans + delta : ans - delta;
      if (wrong >= 0) opts.add(wrong);
    }
    const options = [...opts].sort(() => Math.random() - 0.5);
    set.add(JSON.stringify({ q, options, answer: options.indexOf(ans) }));
  }
  return [...set].map((s) => JSON.parse(s));
}

// 随机口算训练：每次生成一组混合难度的题目（在 main.js 中调用）
function genDrillSet() {
  return [
    ...genAddSub(1, 10, 4, 10),   // 10以内 × 4题
    ...genAddSub(5, 18, 3, 20),   // 20以内 × 3题
    ...genAddSub(11, 90, 3, 100), // 100以内 × 3题
  ];
}

